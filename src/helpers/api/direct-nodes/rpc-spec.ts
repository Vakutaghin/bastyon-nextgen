type Coerce = (arg: unknown) => unknown

// Нестрогие сравнения и `||` — как у прокси: 0, '' и false становятся
// значениями по умолчанию, '1' и 'true' — истиной.
const COERCE: Record<string, Coerce> = {
  str: (arg) => String(arg || ''),
  int: (arg) => parseFloat(String(arg || '0')),
  float: (arg) => parseFloat(String(arg || '0')),
  bool: (arg) =>
    arg === true || arg === 1 || arg === '1' || String(arg ?? '').toLowerCase() === 'true',
  obj: (arg) => {
    if (typeof arg !== 'string') return arg || ''
    try {
      return JSON.parse(arg) as unknown
    } catch {
      return ''
    }
  },
}

/**
 * Параметры метода, приведённые к типам, которых ждёт нода. Не массив
 * (`getapps` шлёт объект) прокси оборачивает в `[объект]` — так же и здесь.
 */
export function coerceParams(method: string, params: unknown): unknown[] {
  const list: unknown[] = params == null ? [] : Array.isArray(params) ? params : [params]
  const spec = PARAM_TYPES[method]
  if (spec === undefined) return [...list]
  const types = spec.split(' ')
  return list.map((arg, i) => {
    const type = types[i]
    if (type === undefined) return arg
    return (COERCE[type] ?? COERCE.str!)(arg)
  })
}

/** Куда отправлять метод: транзакции — на `/post/`, остальное — на `/public/`. */
export function nodePath(method: string): '/post/' | '/public/' {
  return POST_METHODS.has(method) ? '/post/' : '/public/'
}
