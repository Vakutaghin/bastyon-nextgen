/**
 * Оболочка приложения — не текст: список чатов, навигация, боковые панели,
 * шапки и действия карточек, плитки медиа. Её не выделяет протяжка мышью или
 * долгое нажатие на телефоне, ссылки и картинки в ней не перетаскиваются, на
 * iOS не всплывает меню ссылки. Так ведёт себя приложение, а не свёрстанная
 * страница.
 *
 * Кнопки, вкладки, пункты меню и `nav` закрыты глобально (src/style.css), здесь —
 * для контейнеров на div. Текст, который читают и копируют (посты, сообщения,
 * комментарии, профиль, адреса, хеши), сюда не входит. Поля ввода остаются
 * выделяемыми и внутри оболочки — это правило тоже в style.css. Вернуть
 * выделение куску внутри оболочки — `user-select: text` у него.
 *
 * Функцией, как nuxtField: строковая интерполяция — ошибка vue-tsc.
 *
 *   export const SC_ListItem = styled.div`
 *     ${noSelect}
 *     display: flex;
 *   `
 */
export const noSelect = (): string => `
  user-select: none;
  -webkit-touch-callout: none;

  a,
  img {
    -webkit-user-drag: none;
  }
`
