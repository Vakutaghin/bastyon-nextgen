/**
 * Типы для запроса getuserstate API
 *
 * # getuserstate - получение состояния текущего авторизованного пользователя
 *
 * ## Параметры запроса:
 *
 * Параметры передаются как массив с пустым массивом внутри.
 * Метод возвращает состояние текущего авторизованного пользователя.
 *
 * **Пример использования:**
 * ```typescript
 * // Получить состояние текущего пользователя (требует авторизации)
 * const request: GetUserStateRequest = {
 *   method: 'getuserstate',
 *   parameters: [[]],
 *   options: { auth: true } // Обязательна авторизация
 * }
 * ```
 *
 * ## В старом приложении:
 *
 * - Вызывается через `api.rpc('getuserstate', [addresses.join(',')])`
 * - В новом приложении параметры: `[[]]` (пустой массив)
 * - Требует авторизации (подпись запроса обязательна)
 * - Возвращает состояние текущего авторизованного пользователя
 */

import type { BaseRpcRequest } from './common'

/**
 * Параметры запроса getuserstate
 *
 * Пустой массив внутри массива - означает получение состояния текущего авторизованного пользователя.
 * В старом приложении мог передаваться адрес, но в новом приложении используется пустой массив.
 */
export type GetUserStateParameters = [[]]

/**
 * Запрос getuserstate API
 *
 * Используется для получения состояния текущего авторизованного пользователя.
 * Требует авторизации (подпись запроса обязательна).
 */
export interface GetUserStateRequest extends BaseRpcRequest<GetUserStateParameters> {
  /** Название метода */
  method: 'getuserstate'
  /** Параметры запроса - пустой массив (получение текущего пользователя) */
  parameters: GetUserStateParameters
}
