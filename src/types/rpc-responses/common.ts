/**
 * Общие типы для RPC ответов Pocketnet API
 *
 * Все RPC методы возвращают ответы с общей структурой:
 * - result: результат запроса ('success' или 'error')
 * - data: данные ответа (специфичны для каждого метода)
 * - node: узел, обработавший запрос (опционально)
 * - time: метрики времени выполнения (опционально)
 * - error: описание ошибки (если запрос завершился с ошибкой)
 */

/**
 * Результат выполнения RPC запроса
 */
export type RpcResult = 'success' | 'error'

/**
 * Базовые метрики времени выполнения RPC запроса
 *
 * Все значения в миллисекундах (мс).
 * Используется для мониторинга производительности API.
 */
export interface BaseRpcTime {
  /** Время подготовки запроса (мс) */
  preparing: number
  /** Время работы с кешем (мс) */
  cache: number
  /** Время начала обработки (мс) */
  start: number
  /** Время готовности ответа (мс) */
  ready: number
}

/**
 * Метрики обработки узлом (расширенные)
 *
 * Некоторые методы возвращают дополнительные метрики узла.
 * Структура может отличаться в зависимости от метода.
 */
export interface RpcNodeTime {
  /** Время начала RPC запроса (мс) */
  rpcsstart?: number
  /** Время отправки RPC ответа (мс) */
  rpcsend?: number
  /** Дополнительные метрики узла (для расширяемости) */
  [key: string]: unknown
}

/**
 * Базовый интерфейс для всех RPC ответов
 *
 * Все RPC методы возвращают ответы, расширяющие этот интерфейс.
 *
 * @template TData - тип данных ответа (специфичен для каждого метода)
 * @template TTime - тип метрик времени (может расширять BaseRpcTime)
 */
export interface BaseRpcResponse<TData, TTime extends BaseRpcTime = BaseRpcTime> {
  /**
   * Результат запроса
   * 'success' - запрос выполнен успешно
   * 'error' - запрос завершился с ошибкой
   */
  result: RpcResult
  /**
   * Данные ответа
   * Структура зависит от конкретного метода
   */
  data: TData
  /**
   * Узел, обработавший запрос
   * Формат: "IP:PORT" (например, "178.217.159.221:38081")
   * Присутствует не во всех ответах
   */
  node?: string
  /**
   * Метрики времени выполнения запроса
   * Используется для мониторинга производительности API
   * Присутствует не во всех ответах
   */
  time?: TTime
  /**
   * Описание ошибки
   * Присутствует только если result === 'error'
   */
  error?: string
}

/**
 * Стандартные метрики времени с метриками узла
 *
 * Используется в методах, которые возвращают расширенные метрики узла.
 */
export interface StandardRpcTime extends BaseRpcTime {
  /** Метрики обработки узлом */
  node?: RpcNodeTime
}
