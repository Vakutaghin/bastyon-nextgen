/**
 * Типы для ответа RPC метода getaccountearning
 *
 * # getaccountearning - получение заработка аккаунта
 *
 * ## Когда использовать getaccountearning:
 *
 * ✅ **Используйте для:**
 * - Получения информации о заработке пользователя
 * - Отображения статистики доходов
 * - Показывания различных типов заработка (лотерея, донаты, переводы)
 *
 *
 * ## Структура данных:
 *
 * **getaccountearning** возвращает массив информации о заработке:
 * - `address` - адрес пользователя
 * - `amountLottery` - сумма заработка от лотереи
 * - `amountDonation` - сумма заработка от донатов
 * - `amountTransfer` - сумма заработка от переводов
 *
 * ## Особенности:
 *
 * 1. **Типы заработка**:
 *    - `amountLottery` - заработок от участия в лотереях
 *    - `amountDonation` - заработок от донатов от других пользователей
 *    - `amountTransfer` - заработок от переводов
 *
 * 2. **Единицы измерения**:
 *    - Суммы указаны в минимальных единицах (сатоши)
 *    - Для отображения нужно конвертировать в основную единицу
 *
 * 3. **Авторизация**:
 *    - Требует авторизации для получения заработка текущего пользователя
 *
 * ## В старом приложении:
 *
 * - Вызывается через соответствующий RPC метод
 * - Используется для отображения статистики доходов пользователя
 */

import type { BaseRpcResponse, StandardRpcTime } from './common'

/**
 * Информация о заработке аккаунта
 *
 * Содержит различные типы заработка пользователя.
 */
export interface GetAccountEarningItem {
  /**
   * Адрес пользователя (address)
   * Pocketnet адрес пользователя
   */
  address: string
  /**
   * Сумма заработка от лотереи (amountLottery)
   * Сумма в минимальных единицах (сатоши)
   * 0 если нет заработка от лотереи
   */
  amountLottery: number
  /**
   * Сумма заработка от донатов (amountDonation)
   * Сумма в минимальных единицах (сатоши)
   * 0 если нет заработка от донатов
   */
  amountDonation: number
  /**
   * Сумма заработка от переводов (amountTransfer)
   * Сумма в минимальных единицах (сатоши)
   * 0 если нет заработка от переводов
   */
  amountTransfer: number
}

/**
 * Полный ответ RPC метода getaccountearning
 *
 * Используется для получения информации о заработке аккаунта.
 * Требует авторизации.
 *
 * В старом приложении:
 * - Используется для отображения статистики доходов пользователя
 * - Суммы указаны в минимальных единицах (сатоши)
 */
export interface GetAccountEarningResponse extends BaseRpcResponse<GetAccountEarningItem[], StandardRpcTime> {}
