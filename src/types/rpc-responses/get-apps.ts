/**
 * Типы для ответа RPC метода getapps
 *
 * # getapps - получение списка приложений
 *
 * ## Когда использовать getapps:
 *
 * ✅ **Используйте для:**
 * - Получения списка доступных приложений
 * - Отображения каталога приложений
 * - Получения информации о приложениях в системе
 *
 *
 * ## Структура данных:
 *
 * **getapps** возвращает массив приложений.
 * В примере ответа массив пустой, что может означать отсутствие приложений или другую структуру данных.
 *
 * ## Особенности:
 *
 * 1. **Структура приложений**:
 *    - Точная структура данных приложений не определена в примере
 *    - Может содержать информацию о приложениях, их версиях, описаниях и т.д.
 *
 * 2. **Использование**:
 *    - Используется для получения каталога приложений
 *    - Может использоваться для интеграции с внешними приложениями
 *
 * ## В старом приложении:
 *
 * - Вызывается через соответствующий RPC метод
 * - Используется для получения списка доступных приложений
 */

import type { BaseRpcResponse, StandardRpcTime } from './common'

