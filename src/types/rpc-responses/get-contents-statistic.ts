/**
 * Типы для ответа RPC метода getcontentsstatistic
 *
 * # getcontentsstatistic - получение статистики контента пользователя
 *
 * ## Когда использовать getcontentsstatistic:
 *
 * ✅ **Используйте для:**
 * - Получения статистики контента пользователя
 * - Отображения суммарных оценок постов
 * - Получения количества лайков и лайкнувших пользователей
 * - Анализа популярности контента пользователя
 *
 *
 * ## Структура данных:
 *
 * **getcontentsstatistic** возвращает массив статистики контента:
 * - `address` - адрес пользователя
 * - `scoreSum` - суммарная оценка всех постов пользователя
 * - `scoreCnt` - общее количество оценок всех постов пользователя
 * - `countLikers` - количество уникальных пользователей, поставивших лайки
 *
 * ## Особенности:
 *
 * 1. **Оценки**:
 *    - `scoreSum` - сумма всех оценок (лайки - дизлайки) по всем постам пользователя
 *    - `scoreCnt` - общее количество оценок (лайки + дизлайки) по всем постам
 *
 * 2. **Лайкнувшие**:
 *    - `countLikers` - количество уникальных пользователей, поставивших хотя бы один лайк
 *    - Используется для анализа охвата аудитории
 *
 * 3. **Агрегированная статистика**:
 *    - Статистика рассчитывается по всем постам пользователя
 *    - Показывает общую популярность контента пользователя
 *
 * ## В старом приложении:
 *
 * - Вызывается через соответствующий RPC метод
 * - Используется для отображения статистики контента пользователя
 */

import type { BaseRpcResponse, StandardRpcTime } from './common'

/**
 * Статистика контента пользователя из getcontentsstatistic
 *
 * Содержит агрегированную статистику по всем постам пользователя.
 */
export interface GetContentsStatisticItem {
  /**
   * Адрес пользователя (address)
   * Pocketnet адрес пользователя
   */
  address: string
  /**
   * Суммарная оценка (scoreSum)
   * Сумма всех оценок (лайки - дизлайки) по всем постам пользователя
   * Используется для оценки общей популярности контента
   */
  scoreSum: number
  /**
   * Количество оценок (scoreCnt)
   * Общее количество оценок (лайки + дизлайки) по всем постам пользователя
   * Используется для оценки вовлеченности аудитории
   */
  scoreCnt: number
  /**
   * Количество лайкнувших (countLikers)
   * Количество уникальных пользователей, поставивших хотя бы один лайк
   * Используется для анализа охвата аудитории
   */
  countLikers: number
}

/**
 * Полный ответ RPC метода getcontentsstatistic
 *
 * Используется для получения статистики контента пользователя.
 * Не требует авторизации.
 *
 * В старом приложении:
 * - Используется для отображения статистики контента пользователя
 * - Включает агрегированную статистику по всем постам
 */
export interface GetContentsStatisticResponse extends BaseRpcResponse<GetContentsStatisticItem[], StandardRpcTime> {}
