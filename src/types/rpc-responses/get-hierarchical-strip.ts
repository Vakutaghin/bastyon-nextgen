/**
 * Данные ответа gethierarchicalstrip
 *
 * Содержит посты, метаданные видео/аудио и профили пользователей.
 * Отличается от gettopfeed наличием полей `videos` и `users`.
 */


export interface GetHierarchicalStripData {
  /**
   * Высота блока блокчейна (height)
   * Текущая высота блокчейна на момент запроса
   * Используется для синхронизации и проверки актуальности данных
   */
  height: number
  /**
   * Массив постов в иерархической ленте (contents)
   * Отсортированные по времени/иерархии посты
   * Количество постов определяется параметром `count` в запросе
   * Структура идентична постам из gettopfeed
   */
  contents: GetHierarchicalStripPost[]
  /**
   * Метаданные видео/аудио из Peertube API (videos)
   * Объект, где ключ - это peertube URL (например, "peertube://peertube101.pocketnet.app/e8f1d448-9807-4b05-99da-06496092fc53/audio"),
   * а значение - полная информация о видео/аудио из Peertube API
   *
   * Используется для:
   * - Отображения превью видео/аудио
   * - Получения streaming URLs для воспроизведения
   * - Отображения метаданных (длительность, просмотры, лайки)
   * - Скачивания контента
   *
   * ВАЖНО: Это поле присутствует только в gethierarchicalstrip, в gettopfeed его нет
   */
  videos?: Record<string, PeertubeVideoInfo>
  /**
   * Профили пользователей, упомянутых в ленте (users)
   * Массив профилей пользователей для быстрого доступа без дополнительных запросов
   *
   * Включает:
   * - Авторов постов
   * - Авторов комментариев
   * - Других пользователей, связанных с контентом в ленте
   *
   * ВАЖНО: Это поле присутствует только в gethierarchicalstrip, в gettopfeed его нет
   */
  users?: GetTopFeedUserProfile[]
}

/**
 * Время выполнения запроса gethierarchicalstrip
 *
 * Метрики производительности для мониторинга и оптимизации.
 * Все значения в миллисекундах (мс).
 */
export interface GetHierarchicalStripTime {
  /** Время подготовки запроса (мс) */
  preparing: number
  /** Время работы с кешем (мс) */
  cache: number
  /** Время начала обработки (мс) */
  start: number
  /** Время готовности ответа (мс) */
  ready: number
  /** Метрики обработки узлом */
  node?: {
    /** Время начала RPC запроса (мс) */
    rpcsstart?: number
    /** Время отправки RPC ответа (мс) */
    rpcsend?: number
  }
}

/**
 * Полный ответ RPC метода gethierarchicalstrip
 *
 * Используется для получения иерархической/хронологической ленты контента с фильтрацией и пагинацией.
 * Отличается от gettopfeed наличием полей `videos` и `users` в `data`.
 *
 * В старом приложении:
 * - Вызывается через `psdk.node.shares.hierarchical(p, callback, cache, { method: 'gethierarchicalstrip' })`
 * - Результат кешируется в `storage['shares']`
 * - Используется для иерархических лент (подписки, профиль, хронологическая)
 * - Поддерживает пагинацию через параметр `txid`
 * - Видео информация загружается через `loadvideoinfoifneed` и доступна в `data.videos`
 * - Метрики времени выполнения имеют структуру с `rpcsstart` и `rpcsend`
 */
export interface GetHierarchicalStripResponse {
  /** Результат запроса ('success' или 'error') */
  result: 'success' | 'error'
  /**
   * Данные иерархической ленты
   * Включает посты, метаданные видео/аудио и профили пользователей
   */
  data: GetHierarchicalStripData
  /**
   * Узел, обработавший запрос
   * Формат: "IP:PORT" (например, "178.217.159.221:38081")
   */
  node?: string
  /** Метрики времени выполнения запроса */
  time: GetHierarchicalStripTime
  /** Ошибка, если запрос завершился с ошибкой */
  error?: string
}
