/**
 * Типы для ответа RPC метода getlastcomments
 *
 * # getlastcomments - получение последних комментариев
 *
 * ## Когда использовать getlastcomments:
 *
 * ✅ **Используйте для:**
 * - Отображения последних комментариев в системе
 * - Получения свежих комментариев для виджетов
 * - Мониторинга активности комментариев
 * - Отображения последних обсуждений
 *
 *
 * ## Параметры запроса:
 *
 * Метод принимает 3 строковых параметра (обычно все пустые строки для получения последних комментариев).
 *
 * ## Структура данных:
 *
 * **getlastcomments** возвращает массив комментариев:
 * - `id` - уникальный идентификатор комментария (хеш транзакции)
 * - `postid` - ID поста, к которому относится комментарий
 * - `address` - адрес автора комментария
 * - `msg` - JSON строка с сообщением комментария (содержит message, url, images, info)
 * - `parentid` - ID родительского комментария (если это ответ на комментарий)
 * - `answerid` - ID комментария, на который отвечают
 * - `addressContent` - адрес автора поста
 * - `addressCommentParent` - адрес автора родительского комментария
 * - `addressCommentAnswer` - адрес автора комментария, на который отвечают
 * - `scoreUp` - количество лайков
 * - `scoreDown` - количество дизлайков
 * - `reputation` - репутация комментария
 * - `edit` - флаг редактирования (false если не редактировался)
 *
 * ## Особенности:
 *
 * 1. **Структура сообщения**:
 *    - Поле `msg` содержит JSON строку, которую нужно распарсить
 *    - Формат: `{"message":"текст","url":"","images":[],"info":""}`
 *
 * 2. **Иерархия комментариев**:
 *    - `parentid` и `answerid` используются для построения дерева комментариев
 *    - Если комментарий является ответом, `parentid` указывает на родительский комментарий
 *    - `answerid` указывает на комментарий, на который отвечают
 *
 * 3. **Адреса**:
 *    - `address` - автор комментария
 *    - `addressContent` - автор поста
 *    - `addressCommentParent` - автор родительского комментария (если есть)
 *    - `addressCommentAnswer` - автор комментария, на который отвечают (если есть)
 *
 * 4. **Оценки**:
 *    - `scoreUp` - количество лайков комментария
 *    - `scoreDown` - количество дизлайков комментария
 *    - `reputation` - репутация комментария (может отсутствовать)
 *
 * ## В старом приложении:
 *
 * - Вызывается через `api.rpc('getlastcomments', ps)` где `ps` - массив из 3 строк
 * - Используется для виджетов последних комментариев
 * - Результат обрабатывается через `psdk.comment.get()`
 */

import type { BaseRpcResponse, StandardRpcTime } from './common'

/**
 * Структура сообщения комментария
 *
 * Поле `msg` в комментарии содержит JSON строку с этой структурой.
 */
export interface CommentMessage {
  /** Текст комментария */
  message: string
  /** URL (если есть ссылка в комментарии) */
  url: string
  /** Массив URL изображений (если есть изображения) */
  images: string[]
  /** Дополнительная информация */
  info: string
}

/**
 * Комментарий из getlastcomments
 *
 * Представляет последний комментарий в системе.
 * Используется для отображения свежих комментариев и активности.
 */
export interface GetLastComment {
  /**
   * ID комментария (id)
   * Уникальный идентификатор комментария (хеш транзакции)
   * Используется для идентификации и ссылок на комментарий
   */
  id: string
  /**
   * ID поста (postid)
   * Хеш транзакции поста, к которому относится комментарий
   * Используется для навигации к посту
   */
  postid: string
  /**
   * Адрес автора комментария (address)
   * Pocketnet адрес пользователя, создавшего комментарий
   */
  address: string
  /**
   * Сообщение комментария (msg)
   * JSON строка с содержимым комментария
   * Формат: {"message":"текст","url":"","images":[],"info":""}
   * Требует парсинга через JSON.parse()
   */
  msg: string
  /**
   * ID родительского комментария (parentid)
   * Если комментарий является ответом на другой комментарий,
   * содержит ID родительского комментария
   * Пустая строка, если это комментарий первого уровня
   */
  parentid: string
  /**
   * ID комментария, на который отвечают (answerid)
   * Если комментарий является ответом, содержит ID комментария, на который отвечают
   * Пустая строка, если это не ответ
   */
  answerid: string
  /**
   * Адрес автора поста (addressContent)
   * Pocketnet адрес пользователя, создавшего пост
   * Используется для отображения информации об авторе поста
   */
  addressContent: string
  /**
   * Адрес автора родительского комментария (addressCommentParent)
   * Pocketnet адрес пользователя, создавшего родительский комментарий
   * Пустая строка, если нет родительского комментария
   */
  addressCommentParent: string
  /**
   * Адрес автора комментария, на который отвечают (addressCommentAnswer)
   * Pocketnet адрес пользователя, создавшего комментарий, на который отвечают
   * Пустая строка, если это не ответ
   */
  addressCommentAnswer: string
  /**
   * Количество лайков (scoreUp)
   * Количество положительных оценок комментария
   */
  scoreUp: number
  /**
   * Количество дизлайков (scoreDown)
   * Количество отрицательных оценок комментария
   */
  scoreDown: number
  /**
   * Репутация комментария (reputation)
   * Репутация комментария (может отсутствовать в некоторых комментариях)
   */
  reputation?: number
  /**
   * Флаг редактирования (edit)
   * false - комментарий не редактировался
   * true - комментарий был отредактирован
   */
  edit: boolean
}

/**
 * Полный ответ RPC метода getlastcomments
 *
 * Используется для получения последних комментариев в системе.
 * Не требует авторизации.
 *
 * В старом приложении:
 * - Вызывается через `api.rpc('getlastcomments', ps)` где `ps` - массив из 3 строк
 * - Используется для виджетов последних комментариев
 * - Результат обрабатывается через `psdk.comment.get()`
 */
export interface GetLastCommentsResponse extends BaseRpcResponse<GetLastComment[], StandardRpcTime> {}
