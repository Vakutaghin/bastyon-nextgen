/**
 * Типы для ответа RPC метода getnodeinfo
 *
 * # getnodeinfo - получение информации о ноде блокчейна
 *
 * ## Когда использовать getnodeinfo:
 *
 * ✅ **Используйте для:**
 * - Получения информации о текущей ноде блокчейна
 * - Проверки версии ноды
 * - Получения информации о последнем блоке
 * - Проверки состояния сети (chain, netstakeweight)
 * - Получения информации о портах и прокси
 * - Мониторинга состояния блокчейна
 * - Отображения статуса подключения к сети
 *
 *
 * ## Параметры запроса:
 *
 * Метод `getnodeinfo` **не требует параметров** - вызывается с пустым массивом параметров.
 *
 * ## Структура данных:
 *
 * **getnodeinfo** возвращает `GetNodeInfoResponse`:
 * - `version` - версия ноды (например, "0.22.20")
 * - `time` - текущее время ноды (Unix timestamp)
 * - `chain` - название сети ("main" для основной сети, "test" для тестовой)
 * - `netstakeweight` - общий вес стейка в сети (большое число)
 * - `lastblock` - информация о последнем блоке:
 *   * `height` - высота блока
 *   * `hash` - хеш блока
 *   * `time` - время создания блока (Unix timestamp)
 *   * `ntx` - количество транзакций в блоке
 * - `proxy` - флаг, является ли нода прокси (boolean)
 * - `proxies` - массив прокси-серверов (обычно пустой)
 * - `ports` - информация о портах ноды:
 *   * `node` - порт ноды (P2P)
 *   * `api` - порт API (RPC)
 *   * `rest` - порт REST API
 *   * `ws` - порт WebSocket
 *   * `wss` - порт WebSocket Secure
 *   * `staticrpc` - порт статического RPC
 *
 * ## Особенности:
 *
 * 1. **Кеширование**:
 *    - В старом приложении результат кешируется на 55 секунд
 *    - Поле `time` обновляется при каждом запросе (даже из кеша)
 *    - Поле `lastblock` обновляется при каждом запросе
 *    - Используется для оптимизации частых запросов информации о ноде
 *
 * 2. **Версия ноды**:
 *    - Поле `version` содержит версию ноды в формате "major.minor.patch"
 *    - Используется для проверки совместимости и отображения версии в UI
 *
 * 3. **Сеть (chain)**:
 *    - "main" - основная сеть Pocketnet
 *    - "test" - тестовая сеть
 *    - Используется для определения окружения и валидации операций
 *
 * 4. **Net Stake Weight**:
 *    - Общий вес стейка в сети (большое число)
 *    - Используется для оценки безопасности сети
 *    - Чем больше значение, тем более безопасна сеть
 *
 * 5. **Последний блок**:
 *    - Содержит актуальную информацию о последнем блоке
 *    - Используется для синхронизации и проверки актуальности данных
 *    - Поле `height` используется для пагинации и фильтрации контента
 *
 * 6. **Порты**:
 *    - Информация о доступных портах для подключения
 *    - Используется для настройки подключений к ноде
 *    - WebSocket порты (ws, wss) используются для real-time обновлений
 *
 * 7. **Прокси**:
 *    - Флаг `proxy` указывает, является ли нода прокси-сервером
 *    - Массив `proxies` содержит список доступных прокси (обычно пустой)
 *
 * ## В старом приложении:
 *
 * - Вызывается через `node.rpcs('getnodeinfo')` или `nodeManager.info()`
 * - Результат кешируется в `lastinfo` на 55 секунд
 * - Используется для:
 *   * Проверки версии ноды (`self.version = info.version`)
 *   * Определения сети (`self.bchain = info.chain`)
 *   * Получения информации о последнем блоке
 *   * Мониторинга состояния сети
 * - Метрики времени выполнения имеют стандартную структуру
 */

/**
 * Информация о последнем блоке блокчейна
 */
export interface GetNodeInfoLastBlock {
  /**
   * Высота блока (height)
   * Номер последнего блока в блокчейне
   * Используется для синхронизации и пагинации контента
   */
  height: number
  /**
   * Хеш блока (hash)
   * SHA-256 хеш последнего блока
   * Используется для идентификации и проверки целостности
   */
  hash: string
  /**
   * Время создания блока (time)
   * Unix timestamp времени создания последнего блока
   * Используется для отображения времени последнего обновления
   */
  time: number
  /**
   * Количество транзакций в блоке (ntx)
   * Количество транзакций, включенных в последний блок
   * Используется для статистики и мониторинга активности сети
   */
  ntx: number
}

/**
 * Информация о портах ноды
 *
 * Содержит номера портов для различных сервисов ноды.
 * Используется для подключения к ноде через различные протоколы.
 */
export interface GetNodeInfoPorts {
  /**
   * Порт ноды (node)
   * P2P порт для связи между нодами
   * Обычно 37070
   */
  node: number
  /**
   * Порт API (api)
   * RPC порт для API запросов
   * Обычно 38081
   */
  api: number
  /**
   * Порт REST API (rest)
   * Порт для REST API запросов
   * Обычно 38083
   */
  rest: number
  /**
   * Порт WebSocket (ws)
   * Порт для WebSocket подключений (незащищенный)
   * Обычно 8087
   */
  ws: number
  /**
   * Порт WebSocket Secure (wss)
   * Порт для защищенных WebSocket подключений (TLS)
   * Обычно 8887
   */
  wss: number
  /**
   * Порт статического RPC (staticrpc)
   * Порт для статических RPC запросов
   * Обычно 38082
   */
  staticrpc: number
}

/**
 * Данные ответа getnodeinfo
 *
 * Содержит полную информацию о ноде блокчейна, включая версию,
 * состояние сети, последний блок и конфигурацию портов.
 */
export interface GetNodeInfoData {
  /**
   * Версия ноды (version)
   * Версия ноды в формате "major.minor.patch" (например, "0.22.20")
   * Используется для проверки совместимости и отображения версии
   */
  version: string
  /**
   * Текущее время ноды (time)
   * Unix timestamp текущего времени на ноде
   * Обновляется при каждом запросе (даже из кеша)
   */
  time: number
  /**
   * Название сети (chain)
   * "main" для основной сети Pocketnet
   * "test" для тестовой сети
   * Используется для определения окружения
   */
  chain: 'main' | 'test'
  /**
   * Общий вес стейка в сети (netstakeweight)
   * Большое число, представляющее общий вес стейка в сети
   * Используется для оценки безопасности сети
   * Чем больше значение, тем более безопасна сеть
   */
  netstakeweight: number
  /**
   * Информация о последнем блоке (lastblock)
   * Содержит данные о последнем блоке в блокчейне
   * Обновляется при каждом запросе
   */
  lastblock: GetNodeInfoLastBlock
  /**
   * Флаг прокси (proxy)
   * Если true, нода является прокси-сервером
   * Обычно false для обычных нод
   */
  proxy: boolean
  /**
   * Массив прокси-серверов (proxies)
   * Список доступных прокси-серверов
   * Обычно пустой массив
   */
  proxies: unknown[]
  /**
   * Информация о портах (ports)
   * Содержит номера портов для различных сервисов ноды
   * Используется для подключения к ноде
   */
  ports: GetNodeInfoPorts
}

/**
 * Время выполнения запроса getnodeinfo
 *
 * Метрики производительности для мониторинга и оптимизации.
 * Все значения в миллисекундах (мс).
 */
export interface GetNodeInfoTime {
  /** Время подготовки запроса (мс) */
  preparing: number
  /** Время работы с кешем (мс) */
  cache: number
  /** Время начала обработки (мс) */
  start: number
  /** Время готовности ответа (мс) */
  ready: number
  /** Метрики обработки узлом (может быть пустым объектом) */
  node?: Record<string, unknown>
}

/**
 * Полный ответ RPC метода getnodeinfo
 *
 * Используется для получения информации о ноде блокчейна.
 * Не требует авторизации и параметров.
 *
 * В старом приложении:
 * - Вызывается через `node.rpcs('getnodeinfo')` или `nodeManager.info()`
 * - Результат кешируется в `lastinfo` на 55 секунд
 * - Используется для проверки версии, сети и последнего блока
 * - Поле `time` обновляется при каждом запросе (даже из кеша)
 * - Поле `lastblock` обновляется при каждом запросе
 */
export interface GetNodeInfoResponse {
  /** Результат запроса ('success' или 'error') */
  result: 'success' | 'error'
  /**
   * Данные о ноде
   * Содержит версию, состояние сети, последний блок и конфигурацию
   */
  data: GetNodeInfoData
  /**
   * Узел, обработавший запрос
   * Формат: "IP:PORT" (например, "47.215.69.236:38081")
   */
  node?: string
  /** Метрики времени выполнения запроса */
  time: GetNodeInfoTime
  /** Ошибка, если запрос завершился с ошибкой */
  error?: string
}
