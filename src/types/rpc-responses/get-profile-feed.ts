/**
 * Типы для ответа RPC метода getprofilefeed
 *
 * # getprofilefeed - получение ленты профиля пользователя
 *
 * ## Когда использовать getprofilefeed:
 *
 * ✅ **Используйте для:**
 * - Отображения ленты конкретного пользователя
 * - Получения всех постов пользователя
 * - Фильтрации постов пользователя по типу, языку, тегам
 * - Пагинации ленты профиля
 * - Поиска постов пользователя (через keyword)
 *
 *
 * ## Параметры запроса:
 *
 * | Параметр | Тип | Описание | Пример |
 * |----------|-----|----------|--------|
 * | **height** | number | Высота блока (0 = последние посты) | `0` |
 * | **txid** | string | ID транзакции для пагинации ('' = с начала) | `''` |
 * | **count** | number | Количество постов в ответе | `10`, `20`, `50` |
 * | **lang** | string | Язык контента ('ru', 'en', '' = все языки) | `'ru'`, `'en'`, `''` |
 * | **tagsfilter** | string[] | Фильтр по тегам ([] = все теги) | `['политика']` |
 * | **type** | string[] | Тип контента ([] = все типы) | `['video']`, `['share']` |
 * | **tagsexcluded** | string[] | Исключенные теги | `[]` |
 * | **address** | string | Адрес пользователя, чью ленту получаем | `'PJT8eTrx...'` |
 * | **keyword** | string | Ключевое слово для поиска (опционально) | `'новости'` |
 * | **orderby** | string | Поле для сортировки (опционально) | `'time'`, `'scoreSum'` |
 * | **ascdesc** | string | Направление сортировки ('asc' или 'desc') | `'desc'` |
 *
 * ## КЛЮЧЕВЫЕ ОТЛИЧИЯ от gethierarchicalstrip:
 *
 * | Параметр | gethierarchicalstrip | getprofilefeed |
 * |----------|----------------------|----------------|
 * | **Назначение** | Иерархическая лента | Лента конкретного пользователя |
 * | **Фильтрация** | По подпискам/времени | По адресу пользователя |
 * | **Поиск** | ❌ Нет | ✅ Есть (keyword) |
 * | **Сортировка** | По времени | Настраиваемая (orderby, ascdesc) |
 * | **contents** | Только посты | Посты + профили пользователей |
 * | **videos** | ✅ Есть | ❌ Нет (в примере) |
 * | **users** | ✅ Есть | ❌ Нет (в примере) |
 *
 * ## Структура данных:
 *
 * **getprofilefeed** возвращает `GetProfileFeedResponse`:
 * - `height` - текущая высота блока блокчейна
 * - `contents` - массив контента (может содержать посты и профили пользователей):
 *   * Посты имеют структуру идентичную `GetHierarchicalStripPost`
 *   * Профили пользователей имеют структуру `UserProfile`
 *
 * ## Особенности:
 *
 * 1. **Смешанный контент**:
 *    - Массив `contents` может содержать как посты, так и профили пользователей
 *    - Посты имеют поле `type` (video, audio, share, post)
 *    - Профили имеют поле `name` и другие поля UserProfile
 *
 * 2. **Поиск**:
 *    - Параметр `keyword` позволяет искать посты по ключевому слову
 *    - Поиск выполняется в тексте поста (поле `m` и `c`)
 *
 * 3. **Сортировка**:
 *    - `orderby` - поле для сортировки (например, 'time', 'scoreSum')
 *    - `ascdesc` - направление сортировки ('asc' или 'desc')
 *
 * 4. **Пагинация**:
 *    - Используйте `txid` последнего поста для получения следующей страницы
 *    - Для первой загрузки используйте `txid = ''`
 *
 * ## В старом приложении:
 *
 * - Вызывается через `psdk.node.shares.hierarchical(p, callback, cache, { method: 'getprofilefeed' })`
 * - Использует тот же сценарий, что и `gethierarchicalstrip`
 * - Параметры: `{ count, lang, height, tagsfilter, tagsexcluded, type, txid, address, keyword, orderby, ascdesc }`
 * - Результат кешируется в `storage['shares']`
 * - Используется для отображения ленты профиля пользователя
 */

import type { BaseRpcResponse, StandardRpcTime } from './common'
import type { GetHierarchicalStripPost } from './get-hierarchical-strip'
import type { UserProfile } from './user-get'

/**
 * Данные ответа getprofilefeed
 *
 * Содержит посты пользователя и может содержать профили пользователей.
 * Структура contents может быть смешанной (посты + профили).
 */
export interface GetProfileFeedData {
  /**
   * Высота блока блокчейна (height)
   * Текущая высота блокчейна на момент запроса
   */
  height: number
  /**
   * Массив контента (contents)
   * Может содержать:
   * - Посты пользователя (структура GetHierarchicalStripPost)
   * - Профили пользователей (структура UserProfile)
   *
   * Для определения типа элемента:
   * - Если есть поле 'type' - это пост
   * - Если есть поле 'name' - это профиль пользователя
   */
  contents: Array<GetHierarchicalStripPost | UserProfile>
}

/**
 * Полный ответ RPC метода getprofilefeed
 *
 * Используется для получения ленты профиля конкретного пользователя.
 * Не требует авторизации для просмотра чужих профилей.
 *
 * В старом приложении:
 * - Вызывается через `psdk.node.shares.hierarchical(p, callback, cache, { method: 'getprofilefeed' })`
 * - Использует тот же сценарий, что и `gethierarchicalstrip`
 * - Результат кешируется в `storage['shares']`
 * - Поддерживает поиск и сортировку
 */
export interface GetProfileFeedResponse extends BaseRpcResponse<GetProfileFeedData, StandardRpcTime> {}
