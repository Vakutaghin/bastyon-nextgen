/**
 * Типы для ответа RPC метода gettopfeed
 * 
 * # gettopfeed - получение топ-ленты контента
 * 
 * ## Когда использовать gettopfeed:
 * 
 * ✅ **Используйте для:**
 * - Отображения главной ленты с популярным контентом
 * - Получения топ-постов по рейтингу/популярности
 * - Фильтрации контента по тегам и языку
 * - Пагинации ленты (загрузка следующих постов)
 * - Отображения разнообразного контента (видео, посты, изображения)
 * 
 * **Пример использования:**
 * ```typescript
 * // Получить топ-ленту (10 постов, русский язык)
 * const feed = await getByPRC({
 *   method: 'gettopfeed',
 *   parameters: [
 *     0,              // height - высота блока (0 = последние)
 *     '',             // txid - ID транзакции для пагинации ('' = с начала)
 *     10,             // count - количество постов
 *     'ru',           // lang - язык контента
 *     [],             // tagsfilter - фильтр по тегам ([] = все теги)
 *     [],             // type - тип контента ([] = все типы)
 *     [],             // пустой параметр
 *     [],             // пустой параметр
 *     [],             // tagsexcluded - исключенные теги
 *     '',             // пустая строка
 *     10              // depth - глубина выборки
 *   ],
 *   options: { auth: false } // Не требует авторизации
 * })
 * 
 * // Получить следующую страницу (пагинация)
 * const nextFeed = await getByPRC({
 *   method: 'gettopfeed',
 *   parameters: [
 *     0,
 *     feed.data.contents[feed.data.contents.length - 1].txid, // txid последнего поста
 *     10,
 *     'ru',
 *     [],
 *     [],
 *     [],
 *     [],
 *     [],
 *     '',
 *     10
 *   ]
 * })
 * ```
 * 
 * ## Параметры запроса:
 * 
 * | Параметр | Тип | Описание | Пример |
 * |----------|-----|----------|--------|
 * | **height** | number | Высота блока (0 = последние посты) | `0` |
 * | **txid** | string | ID транзакции для пагинации ('' = с начала) | `''` или `'038c9cef...'` |
 * | **count** | number | Количество постов в ответе | `10`, `20`, `50` |
 * | **lang** | string | Язык контента ('ru', 'en', '' = все языки) | `'ru'`, `'en'`, `''` |
 * | **tagsfilter** | string[] | Фильтр по тегам ([] = все теги) | `['природа', 'животные']` |
 * | **type** | string[] | Тип контента ([] = все типы) | `['video']`, `['share']` |
 * | **tagsexcluded** | string[] | Исключенные теги | `['политика']` |
 * | **depth** | number | Глубина выборки (рекомендуется 10) | `10` |
 * 
 * ## Структура данных:
 * 
 * **gettopfeed** возвращает `GetTopFeedResponse`:
 * - `height` - текущая высота блока блокчейна
 * - `contents` - массив постов с полной информацией:
 *   * Базовая информация (hash, txid, id, address, time, type)
 *   * Контент (заголовок `c`, текст `m`, видео `u`, изображения `i`, теги `t`)
 *   * Статистика (scoreCnt, scoreSum, reposted, comments)
 *   * Настройки поста (`s` - разрешения, видео, изображения)
 *   * Версии поста (при редактировании)
 *   * Последний комментарий (`lastComment`)
 *   * Профиль автора (`userprofile` - полный профиль пользователя)
 * 
 * ## Типы контента:
 * 
 * - `'share'` - пост с изображениями/текстом
 *   * Содержит поле `i` (массив URL изображений)
 *   * Может содержать поле `m` (текст описания)
 *   * Поле `u` отсутствует
 * 
 * - `'video'` - видео пост
 *   * Содержит поле `u` (URL видео в формате peertube://...)
 *   * Может содержать поле `m` (описание видео)
 *   * Поле `i` обычно пустое
 * 
 * - `'post'` - текстовый пост
 *   * Содержит только текст (`m`)
 *   * Поля `u` и `i` отсутствуют или пустые
 * 
 * ## Особенности:
 * 
 * 1. **Пагинация**: 
 *    - Используйте `txid` последнего поста для получения следующей страницы
 *    - Для первой загрузки используйте `txid = ''`
 *    - Поле `height` можно использовать для синхронизации
 * 
 * 2. **Фильтрация**: 
 *    - По тегам: `tagsfilter` - включить теги, `tagsexcluded` - исключить теги
 *    - По языку: `lang` - фильтр по языку контента
 *    - По типу: `type` - фильтр по типу контента (video, share, post)
 * 
 * 3. **Кеширование**: 
 *    - В старом приложении результат кешируется в `storage['shares']`
 *    - Ключ кеша формируется из параметров запроса
 *    - Используется для быстрого доступа и офлайн-режима
 * 
 * 4. **Авторизация**: 
 *    - Не обязательна для просмотра ленты
 *    - Если пользователь авторизован, может влиять на ранжирование
 *    - Авторизованные пользователи могут видеть дополнительный контент
 * 
 * 5. **Профили авторов**: 
 *    - Каждый пост включает полный профиль автора (`userprofile`)
 *    - Не требует дополнительных запросов для получения информации об авторе
 *    - Включает аватар, имя, репутацию, бейджи
 * 
 * 6. **Ранжирование**: 
 *    - Посты сортируются по популярности (scoreSum, scoreCnt)
 *    - Учитывается количество комментариев и репостов
 *    - Более свежие посты могут иметь приоритет
 * 
 * ## В старом приложении:
 * 
 * - Вызывается через `psdk.node.shares.gettopfeed(p, callback, cache)`
 * - Параметры: `{ count, lang, height, tagsfilter, tagsexcluded, type, depth, txid }`
 * - Результат кешируется в `storage['shares']`
 * - Используется для главной ленты приложения
 * - Поддерживает пагинацию через `txid`
 * - Метрики времени выполнения имеют структуру с `rpcsstart` и `rpcsend`
 */

/**
 * Профиль пользователя в ответе gettopfeed
 * 
 * Включает полную информацию об авторе поста для отображения в ленте.
 * Структура идентична UserProfile из getuserprofile/getuserstate.
 */
export interface GetTopFeedUserProfile {
  /** Хеш профиля */
  hash: string
  /** Адрес кошелька пользователя */
  address: string
  /** ID пользователя */
  id: number
  /** Имя пользователя */
  name: string
  /** URL аватара пользователя (изображение) */
  i: string
  /** Биография пользователя (JSON строка) */
  b: string
  /** Реферальная ссылка */
  r: string
  /** Количество постов пользователя */
  postcnt: number
  /** Количество удаленных постов */
  dltdcnt: number
  /** Репутация пользователя */
  reputation: number
  /** Количество подписок */
  subscribes_count: number
  /** Количество подписчиков */
  subscribers_count: number
  /** Количество заблокированных пользователей */
  blockings_count: number
  /** Количество пользователей, которые заблокировали */
  blockers_count: number
  /** Количество пользователей, которые лайкнули */
  likers_count: number
  /** Публичные ключи (строка с разделителями) */
  k: string
  /** Описание/о себе (может быть URL-encoded) */
  a: string
  /** Язык профиля */
  l: string
  /** Сайт пользователя (может быть URL-encoded) */
  s: string
  /** Время последнего обновления (Unix timestamp) */
  update: number
  /** Дата регистрации (Unix timestamp) */
  regdate: number
  /** Флаги профиля */
  flags: Record<string, number>
  /** Первоначальные флаги */
  firstFlags: Record<string, unknown>
  /** Количество действий */
  actions: number
  /** Баны */
  bans: Record<string, unknown>
  /** 
   * Бейджи пользователя (badges)
   * Массив строк с названиями бейджей (например, 'shark', 'moderator')
   * Бейджи отображаются рядом с именем пользователя
   */
  badges: string[]
  /** Флаг разработчика (опционально) */
  dev?: boolean
}

/**
 * Последний комментарий к посту
 * 
 * Содержит информацию о последнем комментарии для отображения превью в ленте.
 * Поле `msg` содержит JSON строку с полями: message, url, images, info
 */
export interface GetTopFeedLastComment {
  /** ID комментария (хеш транзакции) */
  id: string
  /** ID комментария (числовой) */
  cid: number
  /** Флаг редактирования */
  edit: boolean
  /** Флаг удаления */
  deleted: boolean
  /** ID поста (хеш транзакции) */
  postid: string
  /** Адрес автора комментария */
  address: string
  /** Время создания (Unix timestamp) */
  time: number
  /** Время обновления (Unix timestamp) */
  timeUpd: number
  /** Номер блока */
  block: number
  /** 
   * Сообщение комментария (JSON строка)
   * Формат: '{"message":"текст","url":"","images":[],"info":""}'
   * Нужно парсить через JSON.parse() для получения структуры
   */
  msg: string
  /** Количество лайков */
  scoreUp: number
  /** Количество дизлайков */
  scoreDown: number
  /** Количество ответов (дочерних комментариев) */
  children: number
  /** Флаги комментария */
  flags: Record<string, unknown>
  /** Флаг доната */
  donation?: string
  /** Сумма доната (в сатоши) */
  amount?: number
}

/**
 * Версия поста (при редактировании)
 * 
 * Хранит историю изменений поста. Каждая версия содержит:
 * - h: высота блока, когда была создана версия
 * - hs: хеш транзакции этой версии
 * 
 * Используется для отслеживания истории редактирования поста.
 */
export interface GetTopFeedPostVersion {
  /** Высота блока */
  h: number
  /** Хеш транзакции */
  hs: string
}

/**
 * Настройки поста
 * 
 * Содержит метаданные и настройки отображения поста.
 * Поле `a` (actions/permissions) определяет доступные действия:
 * - 'i' - изображения
 * - 'u' - видео (URL)
 * - 'cm' - комментарии
 * - 'p' - другие разрешения
 */
export interface GetTopFeedPostSettings {
  /** 
   * Массив разрешений/действий (например, ['i', 'u', 'cm', 'p'])
   * Определяет, какие элементы доступны в посте
   */
  a: string[]
  /** Видео URL */
  v: string
  /** Массив видео */
  videos: unknown[]
  /** URL изображения */
  image: string
  /** Флаг */
  f: string
  /** Контент */
  c: string
  /** Тип */
  t: string
}

/**
 * Пост в ленте gettopfeed
 * 
 * Полная информация о посте для отображения в топ-ленте.
 * Включает контент, статистику, профиль автора и последний комментарий.
 * 
 * В старом приложении используется для:
 * - Отображения постов в главной ленте
 * - Показывания превью контента (изображения, видео)
 * - Отображения статистики (лайки, комментарии, репосты)
 * - Навигации к профилю автора
 * - Отображения последнего комментария
 */
export interface GetTopFeedPost {
  /** Хеш поста (транзакции) */
  hash: string
  /** ID транзакции */
  txid: string
  /** ID поста (числовой) */
  id: number
  /** Адрес автора поста */
  address: string
  /** Время создания поста (Unix timestamp) */
  time: number
  /** Язык поста (например, 'ru', 'en') */
  l: string
  /** Тип поста (например, 'video', 'share', 'post') */
  type: string
  /** 
   * Заголовок/капшн поста (поле 'c' = caption)
   * Краткое описание или заголовок поста
   */
  c: string
  /** 
   * Текст сообщения поста (поле 'm' = message)
   * Полный текст поста, может содержать длинное описание
   */
  m: string
  /** 
   * URL видео (поле 'u' = url)
   * Формат: peertube://host/uuid (например, "peertube://peertube900.pocketnet.app/5a308575-080b-40d9-85b6-ae485e8247a1")
   * Присутствует только для постов типа 'video'
   */
  u?: string
  /** 
   * Теги поста (поле 't' = tags)
   * Массив тегов для категоризации и поиска
   * Пример: ['природа', 'животные', 'фото']
   */
  t: string[]
  /** 
   * Массив URL изображений (поле 'i' = images)
   * URL изображений для постов типа 'share'
   * Каждый URL указывает на изображение на peertube сервере
   */
  i: string[]
  /** Настройки поста */
  s: GetTopFeedPostSettings
  /** 
   * Количество оценок (scoreCnt)
   * Общее количество лайков/дизлайков поста
   */
  scoreCnt: number
  /** 
   * Сумма оценок (scoreSum)
   * Суммарная оценка поста (лайки - дизлайки)
   * Используется для ранжирования в топ-ленте
   */
  scoreSum: number
  /**
   * Оценка текущего пользователя (myVal)
   * Если пользователь авторизован и голосовал за этот пост,
   * поле содержит значение оценки (обычно 1..5)
   */
  myVal?: number
  /** 
   * Количество репостов (reposted)
   * Сколько раз пост был репостнут другими пользователями
   */
  reposted: number
  /** 
   * Количество комментариев (comments)
   * Общее количество комментариев к посту
   */
  comments: number
  /** Версии поста (при редактировании) */
  versions: GetTopFeedPostVersion[]
  /** Флаги поста */
  flags: Record<string, unknown>
  /** 
   * Последний комментарий к посту
   * Используется для отображения превью последнего комментария в ленте
   * Если комментариев нет, может быть пустым объектом
   */
  lastComment: GetTopFeedLastComment
  /** 
   * Профиль пользователя-автора поста
   * Полная информация об авторе для отображения имени, аватара, репутации
   * Структура идентична UserProfile из getuserprofile
   */
  userprofile: GetTopFeedUserProfile
  /** 
   * Флаг редактирования (поле 'edit')
   * Если присутствует и равен 'true', пост был отредактирован
   * В этом случае поле `versions` содержит историю версий
   */
  edit?: string
  /** 
   * ID репоста (если это репост)
   * Если пост является репостом, содержит txid оригинального поста
   */
  repost?: string
}

/**
 * Данные ответа gettopfeed
 * 
 * Содержит текущую высоту блока и массив постов для отображения в ленте.
 */
export interface GetTopFeedData {
  /** 
   * Высота блока блокчейна (height)
   * Текущая высота блокчейна на момент запроса
   * Используется для синхронизации и проверки актуальности данных
   */
  height: number
  /** 
   * Массив постов в ленте (contents)
   * Отсортированные по популярности/рейтингу посты
   * Количество постов определяется параметром `count` в запросе
   */
  contents: GetTopFeedPost[]
}

/**
 * Время выполнения запроса gettopfeed
 * 
 * Метрики производительности для мониторинга и оптимизации.
 * Все значения в миллисекундах (мс).
 */
export interface GetTopFeedTime {
  /** Время подготовки запроса (мс) */
  preparing: number
  /** Время работы с кешем (мс) */
  cache: number
  /** Время начала обработки (мс) */
  start: number
  /** Время готовности ответа (мс) */
  ready: number
  /** Метрики обработки узлом */
  node?: {
    /** Время начала RPC запроса (мс) */
    rpcsstart?: number
    /** Время отправки RPC ответа (мс) */
    rpcsend?: number
  }
}

/**
 * Полный ответ RPC метода gettopfeed
 * 
 * Используется для получения топ-ленты контента с фильтрацией и пагинацией.
 * 
 * В старом приложении:
 * - Вызывается через `psdk.node.shares.gettopfeed(p, callback, cache)`
 * - Результат кешируется в `storage['shares']`
 * - Используется для главной ленты приложения
 * - Поддерживает пагинацию через параметр `txid`
 */
export interface GetTopFeedResponse {
  /** Результат запроса ('success' или 'error') */
  result: 'success' | 'error'
  /** Данные ленты (высота блока и массив постов) */
  data: GetTopFeedData
  /** 
   * Узел, обработавший запрос
   * Формат: "IP:PORT" (например, "178.217.159.221:38081")
   */
  node?: string
  /** Метрики времени выполнения запроса */
  time: GetTopFeedTime
  /** Ошибка, если запрос завершился с ошибкой */
  error?: string
}
