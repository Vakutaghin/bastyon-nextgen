/**
 * Типы для ответа RPC метода getuserstatistic
 *
 * # getuserstatistic - получение статистики пользователя
 *
 * ## Когда использовать getuserstatistic:
 *
 * ✅ **Используйте для:**
 * - Получения статистики пользователя
 * - Отображения количества комментаторов
 * - Получения информации о рефералах
 * - Анализа активности пользователя
 *
 *
 * ## Структура данных:
 *
 * **getuserstatistic** возвращает массив статистики:
 * - `address` - адрес пользователя
 * - `histreferals` - количество исторических рефералов
 * - `commentators` - количество комментаторов
 *
 * ## Особенности:
 *
 * 1. **Рефералы**:
 *    - `histreferals` - количество пользователей, приглашенных данным пользователем
 *    - Используется для реферальной программы
 *
 * 2. **Комментаторы**:
 *    - `commentators` - количество уникальных пользователей, оставивших комментарии к постам пользователя
 *    - Используется для анализа вовлеченности аудитории
 *
 * ## В старом приложении:
 *
 * - Вызывается через соответствующий RPC метод
 * - Используется для отображения статистики пользователя
 */

import type { BaseRpcResponse, StandardRpcTime } from './common'

/**
 * Статистика пользователя из getuserstatistic
 *
 * Содержит информацию о рефералах и комментаторах пользователя.
 */
export interface GetUserStatisticItem {
  /**
   * Адрес пользователя (address)
   * Pocketnet адрес пользователя
   */
  address: string
  /**
   * Количество исторических рефералов (histreferals)
   * Количество пользователей, приглашенных данным пользователем
   * Используется для реферальной программы
   */
  histreferals: number
  /**
   * Количество комментаторов (commentators)
   * Количество уникальных пользователей, оставивших комментарии к постам пользователя
   * Используется для анализа вовлеченности аудитории
   */
  commentators: number
}

/**
 * Полный ответ RPC метода getuserstatistic
 *
 * Используется для получения статистики пользователя.
 * Не требует авторизации.
 *
 * В старом приложении:
 * - Используется для отображения статистики пользователя
 * - Включает информацию о рефералах и комментаторах
 */
export interface GetUserStatisticResponse extends BaseRpcResponse<GetUserStatisticItem[], StandardRpcTime> {}
