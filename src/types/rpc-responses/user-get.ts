/**
 * Типы для ответа getuserprofile API
 *
 * # getuserprofile - получение профиля пользователя(ей) по адресу(ам)
 *
 * ## Когда использовать getuserprofile:
 *
 * ✅ **Используйте для:**
 * - Отображения профиля пользователя (своего или чужого)
 * - Получения базовой информации: имя, аватар, описание, статистика
 * - Просмотра профилей других пользователей (не требует авторизации)
 * - Отображения списков пользователей
 *
 * **Пример использования:**
 * ```typescript
 * // Получить профиль любого пользователя
 * const profile = await getByPRC({
 *   method: 'getuserprofile',
 *   parameters: [['PJT7eTrGXD9uCFВ2QmRmdDJtCBA1R68TRf']],
 *   options: { auth: false } // Не требует авторизации
 * })
 * ```
 *
 * ## Отличия от getuserstate:
 *
 * | Параметр | getuserprofile | getuserstate |
 * |----------|----------------|--------------|
 * | **Авторизация** | Не обязательна | Обязательна |
 * | **Параметры** | Требует адрес(а) | Не требует (возвращает текущего) |
 * | **Данные** | Базовый профиль | Профиль + лимиты + состояние |
 * | **Лимиты** | ❌ Нет | ✅ Есть (score_unspent/spent, post_unspent/spent) |
 * | **Использование** | Отображение профилей | Проверка лимитов, валидация |
 *
 * ## Структура данных:
 *
 * **getuserprofile** возвращает `UserProfile`:
 * - Базовые данные профиля (имя, аватар, описание)
 * - Статистика (подписчики, посты, репутация)
 * - Подписки и подписчики
 * - Контент по типам
 *
 * **getuserstate** возвращает `UserState` (расширяет `UserProfile`):
 * - Все поля из `UserProfile` +
 * - `score_unspent/spent` - лимиты на лайки
 * - `post_unspent/spent` - лимиты на посты
 * - `comment_unspent/spent` - лимиты на комментарии
 * - `trial` - триальный период
 *
 * ## Рекомендации:
 *
 * 1. **Для отображения профиля в UI** → используйте `getuserprofile`
 * 2. **Для проверки лимитов перед действием** → используйте `getuserstate`
 * 3. **Для получения данных текущего пользователя** → можно использовать оба, но `getuserstate` даст больше информации
 * 4. **Для просмотра чужих профилей** → только `getuserprofile`
 *
 * ## В старом приложении:
 *
 * - Вызывается через `api.rpc('getuserprofile', [[address]])`
 * - Результат кешируется в `storage['userInfo']`
 * - Доступ через `psdk.userInfo.get(address)`
 * - Может использоваться для получения профиля любого пользователя (не требует авторизации для просмотра чужих профилей)
 * - Метрики времени выполнения имеют структуру с `rpcswidestart` и `runrpcswideclbks`
 */

/**
 * Подписка пользователя
 *
 * В старом приложении используется для:
 * - Отображения списка подписок пользователя
 * - Проверки приватности подписки (private: "true")
 * - Навигации к профилям подписок
 */
export interface UserSubscribe {
  /** Адрес подписки (опечатка в API: должно быть "address", но API возвращает "adddress") */
  adddress: string
  /** Приватная подписка ("true" если подписка приватная) */
  private?: string
}

/**
 * Подписчик пользователя
 */
export type UserSubscriber = string // Адрес подписчика

/**
 * Контент пользователя (по типам)
 */
export interface UserContent {
  [key: string]: number // Тип контента -> количество
}

/**
 * Флаги пользователя
 */
export interface UserFlags {
  [key: string]: unknown
}

/**
 * Бан пользователя
 */
export interface UserBan {
  [key: string]: unknown
}

/**
 * Блокировка пользователя
 */
export type UserBlocking = string[] // Массив адресов заблокированных пользователей

/**
 * Бейдж пользователя
 */
export type UserBadge = unknown[]

/**
 * Профиль пользователя из getuserprofile/getuserstate
 *
 * Используется как в getuserprofile, так и в getuserstate
 * Структура данных идентична для обоих эндпоинтов
 *
 * В старом приложении поля используются следующим образом:
 * - hash: уникальный идентификатор профиля для кеширования
 * - address: адрес кошелька пользователя (Pocketnet адрес)
 * - id: числовой ID пользователя в системе
 * - name: отображаемое имя пользователя
 * - i: URL аватарки (image) - используется для отображения аватара
 * - b: дополнительные данные в JSON формате (обычно пустой массив "[]")
 * - r: описание профиля (about/description)
 * - postcnt: количество опубликованных постов
 * - dltdcnt: количество удаленных постов
 * - reputation: репутация пользователя (используется для ранжирования)
 * - subscribes_count/subscribers_count: статистика подписок
 * - k: криптографические ключи пользователя (12 ключей через запятую)
 * - content: количество контента по типам (200=посты, 201=комментарии и т.д.)
 */
export interface UserProfile {
  /** Хеш профиля - уникальный идентификатор для кеширования */
  hash: string
  /** Адрес пользователя (Pocketnet адрес, начинается с 'P') */
  address: string
  /** ID пользователя в системе */
  id: number
  /** Имя пользователя (отображаемое имя) */
  name?: string
  /** URL аватарки пользователя (поле 'i' = image) */
  i?: string
  /** Данные в формате JSON (поле 'b', обычно "[]") */
  b?: string
  /** Описание профиля (поле 'r' = about/description) */
  r?: string
  /** Количество постов пользователя */
  postcnt?: number
  /** Количество удаленных постов */
  dltdcnt?: number
  /** Репутация пользователя (используется для ранжирования контента) */
  reputation?: number
  /** Количество подписок пользователя */
  subscribes_count?: number
  /** Количество подписчиков пользователя */
  subscribers_count?: number
  /** Количество пользователей, которых заблокировал этот пользователь */
  blockings_count?: number
  /** Количество пользователей, которые заблокировали этого пользователя */
  blockers_count?: number
  /** Количество пользователей, которые лайкнули контент этого пользователя */
  likers_count?: number
  /**
   * Криптографические ключи пользователя (поле 'k')
   * Строка из 12 публичных ключей, разделенных запятыми
   * Используются для шифрования сообщений и других криптографических операций
   */
  k?: string
  /** Дополнительные данные (поле 'a', обычно пустая строка) */
  a?: string
  /** Язык пользователя (поле 'l', например "ru", "en") */
  l?: string
  /** Статус пользователя (поле 's', обычно пустая строка) */
  s?: string
  /** Время последнего обновления профиля (Unix timestamp) */
  update?: number
  /** Дата регистрации пользователя (Unix timestamp) */
  regdate?: number
  /** Флаги пользователя (расширенные настройки и метаданные) */
  flags?: UserFlags
  /** Первоначальные флаги (флаги при регистрации) */
  firstFlags?: UserFlags
  /** Количество действий пользователя (транзакций в блокчейне) */
  actions?: number
  /** Баны пользователя (информация о банах, если есть) */
  bans?: UserBan
  /** Бейджи пользователя (награды, достижения) */
  badges?: UserBadge
  /** Список подписок пользователя (адреса и настройки приватности) */
  subscribes?: UserSubscribe[]
  /** Список подписчиков пользователя (массив адресов) */
  subscribers?: UserSubscriber[]
  /** Список заблокированных пользователей (массив адресов) */
  blocking?: UserBlocking
  /**
   * Контент пользователя по типам (поле 'content')
   * Ключ - тип контента (200=посты, 201=комментарии и т.д.)
   * Значение - количество контента этого типа
   */
  content?: UserContent
  /**
   * Баланс пользователя в минимальных единицах (аналог сатоши)
   * Используется для отображения баланса кошелька
   */
  balance?: number
  /** Дополнительные поля (для расширяемости API) */
  [key: string]: unknown
}

/**
 * Ответ getuserprofile API
 */
export interface GetUserProfileResponse {
  /** Результат запроса */
  result: 'success' | 'error'
  /** Данные пользователей (массив) */
  data: UserProfile[]
  /** Узел, обработавший запрос */
  node?: string
  /** Время выполнения запроса */
  time?: {
    /** Время подготовки */
    preparing?: number
    /** Время кеширования */
    cache?: number
    /** Время начала */
    start?: number
    /** Время готовности */
    ready?: number
    /** Время обработки узлом */
    node?: {
      /** Время начала RPC */
      rpcswidestart?: number
      /** Выполнение RPC колбэков */
      runrpcswideclbks?: Array<{
        /** Время */
        t: number
        /** Ошибка */
        e: number
        /** Результат */
        r: number
        /** Дополнительно */
        a: number
      }>
    }
  }
  /** Ошибка, если есть */
  error?: string
}

/**
 * Устаревший интерфейс для совместимости
 */
export interface UserGetResponse {
  /** Данные пользователя */
  user?: UserProfile
  /** Ошибка, если есть */
  error?: string
  /** Успешность запроса */
  success?: boolean
}
