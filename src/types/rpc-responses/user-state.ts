/**
 * Типы для ответа getuserstate API
 * 
 * # getuserstate - получение состояния текущего авторизованного пользователя
 * 
 * ## Когда использовать getuserstate:
 * 
 * ✅ **Используйте для:**
 * - Получения состояния **текущего авторизованного пользователя**
 * - Проверки лимитов перед действиями (создание поста, лайк и т.д.)
 * - Валидации доступности функций для пользователя
 * - Получения актуального состояния с лимитами
 * - Загрузки данных при входе/восстановлении сессии
 * 
 * **Пример использования:**
 * ```typescript
 * // Получить состояние текущего пользователя (требует авторизации)
 * const state = await getByPRCWithAuth({
 *   method: 'getuserstate',
 *   parameters: [[]], // Не требует передачи адреса
 *   options: { auth: true } // Обязательна авторизация
 * })
 * 
 * // Проверить, может ли пользователь создать пост
 * if (state.data[0]?.post_unspent > 0) {
 *   // Можно создать пост
 * }
 * ```
 * 
 * ## КЛЮЧЕВЫЕ ОТЛИЧИЯ от getuserprofile:
 * 
 * | Параметр | getuserprofile | getuserstate |
 * |----------|----------------|--------------|
 * | **Авторизация** | Не обязательна | Обязательна |
 * | **Параметры** | Требует адрес(а) | Не требует (возвращает текущего) |
 * | **Данные** | Базовый профиль | Профиль + лимиты + состояние |
 * | **Лимиты** | ❌ Нет | ✅ Есть (score_unspent/spent, post_unspent/spent) |
 * | **Использование** | Отображение профилей | Проверка лимитов, валидация |
 * 
 * ## Структура данных:
 * 
 * **getuserstate** возвращает `UserState` (расширяет `UserProfile`):
 * - Все поля из `UserProfile` (имя, аватар, описание, статистика) +
 * - `score_unspent/spent` - лимиты на лайки
 * - `post_unspent/spent` - лимиты на посты
 * - `comment_unspent/spent` - лимиты на комментарии
 * - `trial` - триальный период
 * 
 * **getuserprofile** возвращает только `UserProfile`:
 * - Базовые данные профиля
 * - Статистика (подписчики, посты, репутация)
 * - Подписки и подписчики
 * - Контент по типам
 * 
 * ## Рекомендации:
 * 
 * 1. **Для получения данных текущего пользователя при загрузке приложения** → используйте `getuserstate`
 * 2. **Для проверки лимитов перед действием** → используйте `getuserstate`
 * 3. **Для отображения профиля в UI** → можно использовать `getuserprofile` или `getuserstate` (оба содержат профиль)
 * 4. **Для просмотра чужих профилей** → только `getuserprofile`
 * 
 * ## В старом приложении:
 * 
 * - Вызывается через `api.rpc('getuserstate', [addresses.join(',')])`
 * - Результат кешируется в `storage['userState']`
 * - Доступ через `psdk.userState.get(address)` или `psdk.userState.getmy()`
 * - Используется для проверки лимитов перед созданием постов/лайков
 * - Метрики времени выполнения имеют структуру с `rpcsstart` и `rpcsend` (отличается от getuserprofile)
 */

import type { UserProfile } from './user-get'

/**
 * Время выполнения запроса getuserstate
 * Отличается от getuserprofile структурой метрик узла
 */
export interface GetUserStateTime {
  /** Время подготовки запроса (мс) */
  preparing?: number
  /** Время кеширования (мс) */
  cache?: number
  /** Время начала обработки (мс) */
  start?: number
  /** Время готовности ответа (мс) */
  ready?: number
  /** Метрики обработки узлом */
  node?: {
    /** Время начала RPC запроса (мс) */
    rpcsstart?: number
    /** Время отправки RPC ответа (мс) */
    rpcsend?: number
  }
}

/**
 * Ответ getuserstate API
 * 
 * Используется для получения состояния текущего авторизованного пользователя.
 * В старом приложении:
 * - Вызывается через api.rpc('getuserstate', [addresses.join(',')])
 * - Результат кешируется в storage['userState']
 * - Доступ через psdk.userState.get(address) или psdk.userState.getmy()
 * 
 * Отличия от getuserprofile:
 * - Требует авторизации (подпись запроса обязательна)
 * - Возвращает состояние пользователя (может включать дополнительные поля состояния)
 * - Метрики времени выполнения имеют другую структуру (rpcsstart/rpcsend вместо rpcswidestart/runrpcswideclbks)
 */
export interface GetUserStateResponse {
  /** Результат запроса */
  result: 'success' | 'error'
  /** 
   * Данные пользователей (массив)
   * Обычно содержит один элемент - состояние текущего авторизованного пользователя
   * 
   * ВАЖНО: Структура данных включает все поля из UserProfile ПЛЮС дополнительные поля состояния:
   * - Лимиты (score_unspent/spent, post_unspent/spent, comment_unspent/spent)
   * - Триальный период (trial)
   * - Другие поля состояния, специфичные для авторизованного пользователя
   * 
   * Используйте тип UserState для типизации элементов массива
   */
  data: UserState[]
  /** 
   * Узел, обработавший запрос
   * Формат: "IP:PORT" (например, "178.159.215.48:38081")
   */
  node?: string
  /** 
   * Метрики времени выполнения запроса
   * Используется для мониторинга производительности API
   */
  time?: GetUserStateTime
  /** Ошибка, если запрос завершился с ошибкой */
  error?: string
}

/**
 * Состояние пользователя
 * 
 * Расширяет UserProfile дополнительными полями состояния, которые доступны только через getuserstate.
 * Эти поля используются для проверки лимитов пользователя и управления доступом к функциям.
 * 
 * В старом приложении используется для:
 * - Проверки лимитов пользователя (changeLimits)
 * - Хранения состояния в storage['userState']
 * - Быстрого доступа к данным через psdk.userState.get(address)
 * - Валидации действий пользователя (validationcurrent)
 */
export interface UserState extends UserProfile {
  /** 
   * Лимиты на лайки/оценки (score)
   * score_unspent - оставшиеся лайки
   * score_spent - потраченные лайки
   */
  score_unspent?: number
  score_spent?: number
  
  /** 
   * Лимиты на посты (post)
   * post_unspent - оставшиеся посты
   * post_spent - потраченные посты
   */
  post_unspent?: number
  post_spent?: number
  
  /** 
   * Лимиты на комментарии (comment)
   * comment_unspent - оставшиеся комментарии
   * comment_spent - потраченные комментарии
   */
  comment_unspent?: number
  comment_spent?: number
  
  /** 
   * Триальный период пользователя
   * Если true, пользователь находится в триальном периоде (может иметь расширенные лимиты)
   */
  trial?: boolean
  
  /** Дополнительные поля состояния (для расширяемости) */
  [key: string]: unknown
}
